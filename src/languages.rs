//! Built-in language support.
//!
//! Every language the editor can highlight, outline and run tooling for is
//! described here in pure Rust: file matching, keywords, comment syntax and
//! the starter template used by "New File". Adding a language is a matter of
//! adding one enum variant plus its small static tables below.

/// A programming (or data/markup) language the editor understands.
#[derive(Clone, Copy, PartialEq, Eq, Debug, Default, Hash)]
pub enum Language {
    #[default]
    Plain,
    Rust,
    Python,
    JavaScript,
    TypeScript,
    Go,
    C,
    Cpp,
    CSharp,
    Java,
    Kotlin,
    Swift,
    Ruby,
    Php,
    Html,
    Css,
    Json,
    Toml,
    Yaml,
    Markdown,
    Shell,
    Sql,
    Xml,
    Dockerfile,
}

