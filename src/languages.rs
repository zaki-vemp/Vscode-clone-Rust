#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_common_extensions() {
        assert_eq!(Language::from_path("src/main.rs"), Language::Rust);
        assert_eq!(Language::from_path("app.py"), Language::Python);
        assert_eq!(Language::from_path("a/b/c.tsx"), Language::TypeScript);
        assert_eq!(Language::from_path("main.go"), Language::Go);
        assert_eq!(Language::from_path("Cargo.toml"), Language::Toml);
        assert_eq!(Language::from_path("README.md"), Language::Markdown);
        assert_eq!(Language::from_path("query.sql"), Language::Sql);
        assert_eq!(Language::from_path("Dockerfile"), Language::Dockerfile);
        assert_eq!(Language::from_path("noext"), Language::Plain);
    }

    #[test]
    fn rust_has_core_keywords() {
        let kw = Language::Rust.keywords();
        for w in ["fn", "let", "mut", "impl", "match", "async", "await"] {
            assert!(kw.contains(&w), "missing keyword {w}");
        }
    }

    #[test]
    fn every_language_has_display_and_badge() {
        for lang in Language::all() {
            assert!(!lang.display().is_empty());
            assert!(!lang.badge().is_empty());
        }
    }
}
