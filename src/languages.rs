    /// Line-comment prefixes, in priority order.
    pub fn line_comments(self) -> &'static [&'static str] {
        match self {
            Language::Python
            | Language::Ruby
            | Language::Shell
            | Language::Yaml
            | Language::Toml
            | Language::Dockerfile => &["#"],
            Language::Sql | Language::Markdown => &["--"],
            Language::CSharp => &["///", "//"],
            _ => &["//"],
        }
    }

    /// (open, close) block comment delimiters, if the language has them.
    pub fn block_comment(self) -> Option<(&'static str, &'static str)> {
        match self {
            Language::Python => Some(("'''", "'''")),
            Language::Html | Language::Xml => Some(("<!--", "-->")),
            Language::Css => Some(("/*", "*/")),
            Language::Markdown | Language::Yaml | Language::Toml | Language::Shell => None,
            Language::Plain | Language::Json | Language::Dockerfile => None,
            _ => Some(("/*", "*/")),
        }
    }

